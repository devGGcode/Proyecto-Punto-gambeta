-- Email del usuario autenticado, normalizado.
create or replace function public.portal_email()
returns text
language sql
stable
as $$
  select lower(trim(coalesce(auth.jwt() ->> 'email', '')));
$$;

-- ¿El usuario autenticado es staff del gym?
-- SECURITY DEFINER para poder leer portal_staff sin recursión de RLS.
create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.portal_staff s
    where lower(trim(s.email)) = public.portal_email()
  );
$$;

-- ID del socio dueño del email autenticado.
create or replace function public.current_socio_id()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select s.id::text
  from public.socios s
  where lower(trim(s.mail)) = public.portal_email()
  limit 1;
$$;

revoke all on function public.portal_email() from public;
revoke all on function public.is_staff() from public;
revoke all on function public.current_socio_id() from public;
grant execute on function public.portal_email() to authenticated;
grant execute on function public.is_staff() to authenticated;
grant execute on function public.current_socio_id() to authenticated;

