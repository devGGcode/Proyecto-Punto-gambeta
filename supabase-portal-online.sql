-- Devuelve sólo los conteos de cada clase (no expone quién reservó).
create or replace function public.portal_clase_ocupacion()
returns table (clase_id bigint, activos bigint, espera bigint)
language sql
stable
security definer
set search_path = public
as $$
  select c.id as clase_id,
         count(*) filter (where i.clase_id is not null and coalesce(i.espera,false) = false) as activos,
         count(*) filter (where i.clase_id is not null and coalesce(i.espera,false) = true) as espera
  from public.clases c
  left join public.insc i on i.clase_id = c.id
  group by c.id;
$$;

revoke all on function public.portal_clase_ocupacion() from public;
grant execute on function public.portal_clase_ocupacion() to authenticated;

-- Reserva/cancela el cupo del socio autenticado de forma atómica.
create or replace function public.portal_reservar_clase(p_clase_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_socio text := public.current_socio_id();
  v_cupo int;
  v_archivada boolean;
  v_activos int;
  v_espera boolean;
  v_existe boolean;
  v_promovido text;
begin
  if v_socio is null then
    raise exception 'No autorizado';
  end if;

  select cupo, coalesce(archivada,false)
    into v_cupo, v_archivada
    from public.clases
   where id = p_clase_id;

  if not found or v_archivada then
    raise exception 'Clase no disponible';
  end if;

  if exists (
    select 1 from public.clase_exc
     where clase_id = p_clase_id
       and fecha = current_date
       and cancelada = true
  ) then
    raise exception 'Clase cancelada';
  end if;

  select exists(
    select 1 from public.insc
     where clase_id = p_clase_id and socio_id = v_socio
  ) into v_existe;

  if v_existe then
    delete from public.insc
     where clase_id = p_clase_id and socio_id = v_socio;

    select socio_id into v_promovido
      from public.insc
     where clase_id = p_clase_id and espera = true
     order by ts asc, socio_id asc
     limit 1;

    if v_promovido is not null then
      update public.insc
         set espera = false
       where clase_id = p_clase_id and socio_id = v_promovido;
    end if;

    return jsonb_build_object(
      'accion','cancelada',
      'promovido',v_promovido,
      'activos',(select count(*) from public.insc where clase_id = p_clase_id and espera = false),
      'cupo',v_cupo
    );
  end if;

  select count(*) into v_activos
    from public.insc
   where clase_id = p_clase_id and espera = false;

  v_espera := v_activos >= coalesce(v_cupo,0);

  insert into public.insc (clase_id, socio_id, espera, ts)
  values (p_clase_id, v_socio, v_espera, (extract(epoch from clock_timestamp())*1000)::bigint);

  return jsonb_build_object(
    'accion', case when v_espera then 'espera' else 'reservada' end,
    'activos', v_activos + case when v_espera then 0 else 1 end,
    'cupo', v_cupo
  );
end;
$$;

revoke all on function public.portal_reservar_clase(bigint) from public;
grant execute on function public.portal_reservar_clase(bigint) to authenticated;

-- Refuerza el cupo incluso si alguien intenta insertar directo por la API.
create or replace function public.portal_insc_cupo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_cupo int;
  v_activos int;
begin
  if public.is_staff() then
    return new;
  end if;

  select cupo into v_cupo from public.clases where id = new.clase_id;
  if v_cupo is null then
    raise exception 'Clase no disponible';
  end if;

  select count(*) into v_activos
    from public.insc
   where clase_id = new.clase_id
     and espera = false
     and socio_id <> new.socio_id;

  if v_activos >= v_cupo then
    new.espera := true;
  end if;

  return new;
end;
$$;

revoke all on function public.portal_insc_cupo() from public;

drop trigger if exists portal_insc_cupo on public.insc;
create trigger portal_insc_cupo
  before insert or update of espera, clase_id, socio_id on public.insc
  for each row execute function public.portal_insc_cupo();

