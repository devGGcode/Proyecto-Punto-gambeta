-- Excepciones de clases (clase cancelada / profesor suplente en una fecha)
create table if not exists public.clase_exc (
  clase_id bigint not null references public.clases(id) on delete cascade,
  fecha date not null,
  cancelada boolean not null default false,
  profe text not null default '',
  primary key (clase_id, fecha)
);

-- Solicitudes de renovación enviadas desde el portal
create table if not exists public.renovaciones (
  id text primary key,
  socio_id text references public.socios(id) on delete cascade,
  dni text not null default '',
  nombre text not null default '',
  plan text not null default '',
  vence date,
  fecha date not null default current_date,
  ts bigint not null default 0,
  estado text not null default 'pendiente',
  origen text not null default 'portal',
  resuelta_en date
);

